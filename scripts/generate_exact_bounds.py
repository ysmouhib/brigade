"""Regenerates `HJBrigade/Theorems/ExactBounds.lean` from `brigade.skeptic_hj` and `brigade.hypergraph`."""

from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from brigade.hypergraph import emit_schur_lean, emit_vdw_cert_lean, solve_schur, solve_vdw_cert  # noqa: E402
from brigade.skeptic_hj import emit_lower_bound_lean, emit_upper_bound_lean, solve_hj  # noqa: E402


def main() -> None:
    parts = [
        "import HJBrigade.Core.Line",
        "import HJBrigade.Certificates.CertTree",
        "import HJBrigade.Certificates.HypergraphCert",
        "import HJBrigade.Reductions.VanDerWaerden",
        "import HJBrigade.Reductions.Schur",
        "",
        "/-!",
        "# Machine-Checked Exact Finite Hales–Jewett, Van der Waerden & Schur Bounds",
        "",
        "Generated by `scripts/generate_exact_bounds.py` via DPLL + symmetry breaking,",
        "and verified directly inside Lean 4's kernel (zero `sorry`, zero `native_decide`).",
        "-/",
        "",
        "namespace HJBrigade",
        "",
    ]

    r222 = solve_hj(2, 2, 2)
    parts.append(emit_upper_bound_lean(r222, theorem_name="hj_2_2_cert_le_2"))

    r332 = solve_hj(3, 3, 2)
    parts.append(emit_lower_bound_lean(r332, theorem_name="hj_3_2_gt_3"))

    r432 = solve_hj(4, 3, 2)
    parts.append(emit_upper_bound_lean(r432, theorem_name="hj_3_2_le_4"))

    parts.append(
        "theorem hj_3_2_exact : ¬ HJUpper 3 3 2 ∧ HJUpper 4 3 2 :=\n"
        "  ⟨hj_3_2_gt_3, hj_3_2_le_4⟩\n"
    )

    r442 = solve_hj(4, 4, 2)
    assert r442.status == "SAT_LINE_FREE"
    parts.append(emit_lower_bound_lean(r442, theorem_name="hj_4_2_gt_4"))

    r433 = solve_hj(4, 3, 3)
    assert r433.status == "SAT_LINE_FREE"
    parts.append(emit_lower_bound_lean(r433, theorem_name="hj_3_3_gt_4"))

    parts.append(
        "private def vdw_8_3_2_witness (i : Fin 8) : Fin 2 :=\n"
        "  ⟨([0, 0, 1, 1, 0, 0, 1, 1].getD i.val 0) % 2, Nat.mod_lt _ (by decide)⟩\n\n"
        "theorem vdw_3_2_gt_8 : ¬ HasMonoAP 8 3 2 := by\n"
        "  intro h\n"
        "  have h8 : HasMonoAPFor 8 3 2 vdw_8_3_2_witness := (hasMonoAP_iff_for 8 3 2).mp h vdw_8_3_2_witness\n"
        "  revert h8\n"
        "  decide\n"
    )

    parts.append(
        "theorem hj_4_3_2_implies_vdw_9 : HasMonoAP 9 3 2 := by\n"
        "  simpa using hj_implies_vdw (d := 4) (k := 2) (r := 2) hj_3_2_le_4\n\n"
        "theorem vdw_3_2_exact : ¬ HasMonoAP 8 3 2 ∧ HasMonoAP 9 3 2 :=\n"
        "  ⟨vdw_3_2_gt_8, hj_4_3_2_implies_vdw_9⟩\n"
    )

    # W(4, 2) = 35 via HyperCert reflection
    w34 = solve_vdw_cert(34, 4, 2)
    assert w34.status == "SAT_FREE", f"Unexpected W(4,2)>34 status: {w34.status}"
    parts.append(emit_vdw_cert_lean(w34, theorem_name="vdw_4_2_gt_34"))

    w35 = solve_vdw_cert(35, 4, 2, root=17, walksat_steps=1500)
    assert w35.status == "UNSAT_MONO", f"Unexpected W(4,2)<=35 status: {w35.status}"
    parts.append(emit_vdw_cert_lean(w35, theorem_name="vdw_4_2_le_35"))

    parts.append(
        "theorem vdw_4_2_exact : ¬ HasMonoAP 34 4 2 ∧ HasMonoAP 35 4 2 :=\n"
        "  ⟨vdw_4_2_gt_34, vdw_4_2_le_35⟩\n"
    )

    # W(3, 3) > 26 (exact value W(3,3) = 27)
    w26_3 = solve_vdw_cert(26, 3, 3, walksat_steps=12000)
    assert w26_3.status == "SAT_FREE", f"Unexpected W(3,3)>26 status: {w26_3.status}"
    parts.append(emit_vdw_cert_lean(w26_3, theorem_name="vdw_3_3_gt_26"))

    # S(3) = 14 via HyperCert reflection
    s13 = solve_schur(13, 3)
    assert s13.status == "SAT_FREE", f"Unexpected S(3)>13 status: {s13.status}"
    parts.append(emit_schur_lean(s13, theorem_name="schur_3_gt_13"))

    s14 = solve_schur(14, 3, walksat_steps=1500)
    assert s14.status == "UNSAT_MONO", f"Unexpected S(3)<=14 status: {s14.status}"
    parts.append(emit_schur_lean(s14, theorem_name="schur_3_le_14"))

    parts.append(
        "theorem schur_3_exact : ¬ HasMonoSchur 13 3 ∧ HasMonoSchur 14 3 :=\n"
        "  ⟨schur_3_gt_13, schur_3_le_14⟩\n\n"
        "end HJBrigade\n"
    )

    out_path = ROOT / "HJBrigade" / "Theorems" / "ExactBounds.lean"
    out_path.write_text("\n".join(parts), encoding="utf-8")
    print(
        f"Wrote {out_path} "
        f"(HJ(3,2)={r432.nodes_explored}, W(4,2)={w35.nodes_explored}, S(3)={s14.nodes_explored} nodes)"
    )


if __name__ == "__main__":
    main()
