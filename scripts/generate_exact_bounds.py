"""Regenerates `HJBrigade/Theorems/ExactBounds.lean` from `brigade.skeptic_hj`."""

from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from brigade.skeptic_hj import emit_lower_bound_lean, emit_upper_bound_lean, solve_hj


def main() -> None:
    parts = [
        "import HJBrigade.Core.Line",
        "import HJBrigade.Certificates.CertTree",
        "import HJBrigade.Reductions.VanDerWaerden",
        "",
        "/-!",
        "# Machine-Checked Exact Finite Hales–Jewett & Van der Waerden Bounds",
        "",
        "Generated by `scripts/generate_exact_bounds.py` via DPLL + symmetry breaking,",
        "and verified directly inside Lean 4's kernel (zero `sorry`, zero `native_decide`).",
        "-/",
        "",
        "namespace HJBrigade",
        "",
    ]

    r222 = solve_hj(2, 2, 2)
    parts.append(emit_upper_bound_lean(r222, theorem_name="hj_2_2_cert_le_2"))

    r332 = solve_hj(3, 3, 2)
    parts.append(emit_lower_bound_lean(r332, theorem_name="hj_3_2_gt_3"))

    r432 = solve_hj(4, 3, 2)
    parts.append(emit_upper_bound_lean(r432, theorem_name="hj_3_2_le_4"))

    parts.append(
        "theorem hj_3_2_exact : ¬ HJUpper 3 3 2 ∧ HJUpper 4 3 2 :=\n"
        "  ⟨hj_3_2_gt_3, hj_3_2_le_4⟩\n"
    )

    parts.append(
        "private def vdw_8_3_2_witness (i : Fin 8) : Fin 2 :=\n"
        "  ⟨([0, 0, 1, 1, 0, 0, 1, 1].getD i.val 0) % 2, Nat.mod_lt _ (by decide)⟩\n\n"
        "theorem vdw_3_2_gt_8 : ¬ HasMonoAP 8 3 2 := by\n"
        "  intro h\n"
        "  have h8 : HasMonoAPFor 8 3 2 vdw_8_3_2_witness := (hasMonoAP_iff_for 8 3 2).mp h vdw_8_3_2_witness\n"
        "  revert h8\n"
        "  decide\n"
    )

    parts.append(
        "theorem hj_4_3_2_implies_vdw_9 : HasMonoAP 9 3 2 := by\n"
        "  simpa using hj_implies_vdw (d := 4) (k := 2) (r := 2) hj_3_2_le_4\n\n"
        "theorem vdw_3_2_exact : ¬ HasMonoAP 8 3 2 ∧ HasMonoAP 9 3 2 :=\n"
        "  ⟨vdw_3_2_gt_8, hj_4_3_2_implies_vdw_9⟩\n\n"
        "end HJBrigade\n"
    )

    out_path = ROOT / "HJBrigade" / "Theorems" / "ExactBounds.lean"
    out_path.write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {out_path} ({r432.nodes_explored} nodes in HJ(3,2) certificate)")


if __name__ == "__main__":
    main()
